"""Golden of the Azure DevOps back-end with recorded fictional responses (technique-azure-devops.md section 8, which
follows technique-jira-xray.md section 10.1; methodology 15; plan 10.3).

Each folder of tests/golden/azure_devops/ is a scenario, written by hand: scenario.json (the command, the expected
exit codes, the runs), the batch under runs/, optionally tracker/ids.yaml, and per run responses*.json (Azure
DevOps' answers, in order, each with the request it answers: method and path, the query included when given) and
expected_requests*.json (the exact list of requests: method, URL with its query, the authentication scheme — never
the token —, the media type and the body, JSON Patch included; a credential's value would appear as <NAME>). A
project.yaml in the scenario replaces the shared tests/golden/azure_devops/project.yaml. The .env is written here
with the fictional value of tests/tracker_kit.py (a .env is never committed).

The test: a dry run first (no writing request, the exit given), then each run with --yes and --now through the fake
transport, whose requests must equal the expected list exactly (order included) and use every response; then the
same command again makes no request at all. The expected lists are never generated by the test:
`python tests/test_azure_devops_golden.py --print <scenario>` only shows the requests made, to help whoever writes one.

python -m unittest discover -s tests   (from the root of qa-assistant)
"""

import json
import os
import shutil
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [ROOT, os.path.join(ROOT, "scripts"), HERE]

from tracker_kit import ADO_ENV

from adapters.tracker import cli
from adapters.tracker.testing import FakeTransport

GOLDEN = os.path.join(HERE, "golden", "azure_devops")
NOW = "2026-09-28T12:00:00"


def scenarios():
    return sorted(d for d in os.listdir(GOLDEN) if os.path.isfile(os.path.join(GOLDEN, d, "scenario.json")))


def _names(obj):
    """Credentials' values -> <NAME> (the golden files never have a value, even a fictional one)."""
    if isinstance(obj, dict):
        return {k: _names(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_names(v) for v in obj]
    if isinstance(obj, str):
        for name, value in ADO_ENV.items():
            obj = obj.replace(value, f"<{name}>")
    return obj


def normalize(req) -> dict:
    auth = req.headers.get("Authorization")
    ctype = req.headers.get("Content-Type")
    return {"method": req.method, "url": req.url, "auth": auth.split(" ")[0] if auth else None,
            "content_type": ctype.split(";")[0].strip() if ctype else None,
            "body": None if req.body is None else _names(json.loads(req.body.decode("utf-8")))}


class Golden(unittest.TestCase):
    def workspace(self, name):
        tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmp, True)
        src = os.path.join(GOLDEN, name)
        for entry in os.listdir(src):
            path = os.path.join(src, entry)
            if os.path.isdir(path):
                shutil.copytree(path, os.path.join(tmp, entry))
        project = os.path.join(src, "project.yaml")
        shutil.copy(project if os.path.isfile(project) else os.path.join(GOLDEN, "project.yaml"),
                    os.path.join(tmp, "project.yaml"))
        with open(os.path.join(tmp, ".env"), "w", encoding="utf-8") as f:
            f.writelines(f"{k}={v}\n" for k, v in ADO_ENV.items())
        return tmp

    def load(self, name, file):
        with open(os.path.join(GOLDEN, name, file), encoding="utf-8") as f:
            return json.load(f)

    def run_cli(self, ws, args, responses, fail_at=None):
        fake = FakeTransport(responses, fail_at=fail_at)
        lines = []
        code = cli.main([ws, *args], transport=fake, sleep=lambda s: None, printer=lines.append)
        return code, fake, "\n".join(lines)

    def check(self, name):
        sc = self.load(name, "scenario.json")
        command = sc["command"]
        first = sc["runs"][0]
        # 1. the dry run: only reads (the resolution), in a workspace of its own
        ws = self.workspace(name)
        code, fake, out = self.run_cli(ws, command, self.load(name, first["responses"]))
        self.assertEqual(code, sc["dry_run_exit"], out)
        self.assertEqual([normalize(r) for r in fake.writes()], [], "the dry run made a writing request")
        self.assertFalse(os.path.exists(os.path.join(ws, "tracker", "sent")), "the dry run wrote a record")
        # 2. the runs with --yes: exactly the expected requests
        ws = self.workspace(name)
        for n, run in enumerate(sc["runs"], 1):
            code, fake, out = self.run_cli(ws, [*command, "--yes", "--now", NOW], self.load(name, run["responses"]),
                                           run.get("fail_at"))
            made = [normalize(r) for r in fake.requests]
            expected = self.load(name, run["expected"])
            self.assertEqual(len(made), len(expected), f"run {n}: {len(made)} requests made\n{out}")
            for i, (got, want) in enumerate(zip(made, expected, strict=True), 1):
                self.assertEqual(got, want, f"run {n}, request {i}\n{out}")
            self.assertEqual(code, run["exit"], out)
            self.assertEqual(fake.left, 0, f"run {n}: responses not used")
        # 3. the same command again: no request at all (the record is complete)
        if sc["runs"][-1]["exit"] in (0, 5):
            code, fake, out = self.run_cli(ws, [*command, "--yes"], [])
            self.assertEqual((code, fake.requests), (0, []), out)
            with open(os.path.join(ws, "tracker", "sent", os.path.basename(command[1]).rsplit(".", 1)[0] + ".json"),
                      encoding="utf-8") as f:
                record = json.load(f)
            self.assertEqual([w["kind"] for w in record["writes"]], sc["record"])
            for value in ADO_ENV.values():
                self.assertNotIn(value, json.dumps(record))

    def test_scenarios(self):
        names = scenarios()
        self.assertEqual(names, ["bugs", "conflict", "interrupted", "question", "results_only"])
        for name in names:
            with self.subTest(scenario=name):
                self.check(name)


def _print(name):
    """Shows the requests each run of a scenario makes (a helper for whoever writes a golden; never its source)."""
    g = Golden()
    g.addCleanup = lambda *a, **k: None
    sc = g.load(name, "scenario.json")
    ws = g.workspace(name)
    for run in sc["runs"]:
        code, fake, out = g.run_cli(ws, [*sc["command"], "--yes", "--now", NOW], g.load(name, run["responses"]),
                                    run.get("fail_at"))
        print(out)
        print(json.dumps([normalize(r) for r in fake.requests], ensure_ascii=False, indent=1))
        print("exit", code)


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--print":
        _print(sys.argv[2])
    else:
        unittest.main()
